# ── Helpers ──
def heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

H1_ORPHAN = (A4[1] - 2 * MARGIN) * 0.15

def major(text):
    return [CondPageBreak(H1_ORPHAN), heading(text, h1, 0),
            HRFlowable(width='100%', thickness=1.1, color=ACCENT, spaceBefore=0, spaceAfter=10)]

def sub(text):
    return [heading(text, h2, 1)]

def tbl(headers, rows, ratios, caption_text=None, mono_cols=()):
    data = [[Paragraph('<b>%s</b>' % c, th) for c in headers]]
    for r in rows:
        cells = []
        for i, c in enumerate(r):
            cells.append(Paragraph(str(c), td_m if i in mono_cols else td))
        data.append(cells)
    widths = [x * AVAIL for x in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor('#c3c9cf')),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 8), t]
    if caption_text:
        out += [Paragraph(caption_text, caption)]
    out += [Spacer(1, 8)]
    return out

def callout_row(items):
    cells, w = [], AVAIL / len(items)
    for big, label in items:
        inner = Table([[Paragraph('<b>%s</b>' % big, stat_big)], [Paragraph(label, stat_label)]],
                      colWidths=[w - 12])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), BG_PAGE),
            ('BOX', (0, 0), (-1, -1), 0.8, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 8), ('BOTTOMPADDING', (0, 1), (-1, 1), 8),
            ('TOPPADDING', (0, 1), (-1, 1), 2), ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
        ]))
        cells.append(inner)
    outer = Table([cells], colWidths=[w] * len(items), hAlign='CENTER')
    outer.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                               ('LEFTPADDING', (0, 0), (-1, -1), 4),
                               ('RIGHTPADDING', (0, 0), (-1, -1), 4)]))
    return [Spacer(1, 6), outer, Spacer(1, 10)]

